// Bundles the CLI (and its runtime deps + built-in rules) into ONE dependency-free file that the
// GitHub Action executes directly: `node action-dist/cli.js`. The bundle is committed so `uses:` needs
// no npm install / build step. CI fails if it is stale (npm run bundle && git diff --exit-code action-dist).
//
//   node scripts/bundle.mjs [--outdir <dir>]      (default: action-dist)
import { build } from "esbuild";
import { chmodSync, copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const i = process.argv.indexOf("--outdir");
const outdir = resolve(root, i > 0 ? process.argv[i + 1] : "action-dist");
mkdirSync(outdir, { recursive: true });

await build({
  entryPoints: [join(root, "src/cli.ts")],
  outfile: join(outdir, "cli.js"),
  bundle: true,
  platform: "node",
  target: "node18",
  format: "cjs",
  legalComments: "none",
  logLevel: "warning",
  banner: { js: "// GENERATED by scripts/bundle.mjs from src/ - do not edit. Third-party licenses: ./THIRD_PARTY_LICENSES.txt" },
});
chmodSync(join(outdir, "cli.js"), 0o755);

const semverPkg = JSON.parse(readFileSync(join(root, "node_modules/semver/package.json"), "utf8"));
writeFileSync(
  join(outdir, "THIRD_PARTY_LICENSES.txt"),
  `This bundle includes semver@${semverPkg.version} (${semverPkg.license}):\n\n` + readFileSync(join(root, "node_modules/semver/LICENSE"), "utf8"),
);
copyFileSync(join(root, "LICENSE"), join(outdir, "LICENSE"));
